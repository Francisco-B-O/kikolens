"""Receta: la lista ordenada de pasos (limpieza y transformación) aplicados a un dataset. Se puede guardar como
JSON, volver a aplicar a un archivo nuevo con las mismas columnas y exportar como script de Python."""
import json
from dataclasses import dataclass, field
from datetime import datetime, timezone

import pandas as pd

from kikolens.analyze import cleaning, privacy, quality, transform

FORMAT_VERSION = 1
OPERATIONS = {**quality.OPERATIONS, **transform.OPERATIONS, **cleaning.OPERATIONS, **privacy.OPERATIONS}
DATASET_OPERATIONS = transform.DATASET_OPERATIONS


def _jsonable(value):
    """Convierte parámetros a tipos de JSON (numpy, tuplas, etc.)."""
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_jsonable(v) for v in value]
    if hasattr(value, "item") and not isinstance(value, (str, bytes)):
        try:
            return value.item()
        except (ValueError, AttributeError):
            pass
    return value


def apply_operation(df: pd.DataFrame, name: str, /, datasets: dict | None = None, **params):
    """Ejecuta una operación por nombre. Devuelve (nuevo_df, mensaje); el original no se modifica."""
    if name not in OPERATIONS:
        raise ValueError(f"Unknown operation '{name}'.")
    if name in DATASET_OPERATIONS:
        other = params.get("other")
        if not datasets or other not in datasets:
            raise ValueError(f"The dataset '{other}' is needed for this step but was not provided.")
        params = {**params, "other_df": datasets[other]}
    try:
        return OPERATIONS[name](df, **params)
    except TypeError as e:
        raise ValueError(f"Invalid parameters for '{name}': {e}") from None


@dataclass
class Step:
    op: str
    params: dict = field(default_factory=dict)
    message: str = ""

    def to_dict(self) -> dict:
        return {"op": self.op, "params": _jsonable(self.params), "message": self.message}


@dataclass
class Recipe:
    steps: list = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.steps)

    def add(self, op: str, params: dict, message: str = "") -> None:
        self.steps.append(Step(op, dict(params), message))

    def pop(self) -> None:
        if self.steps:
            self.steps.pop()

    def clear(self) -> None:
        self.steps.clear()

    @property
    def required_datasets(self) -> list:
        return sorted({s.params["other"] for s in self.steps if s.op in DATASET_OPERATIONS and "other" in s.params})

    def apply(self, df: pd.DataFrame, datasets: dict | None = None):
        """Reproduce todos los pasos sobre `df`. Devuelve (resultado, mensajes). Falla con el paso que no encaja."""
        log = []
        for i, step in enumerate(self.steps, 1):
            try:
                df, message = apply_operation(df, step.op, datasets=datasets, **step.params)
            except ValueError as e:
                raise ValueError(f"Step {i} ({step.op}) failed: {e}") from None
            log.append(message)
        return df, log

    def describe(self) -> pd.DataFrame:
        return pd.DataFrame([{"step": i, "operation": s.op, "result": s.message} for i, s in enumerate(self.steps, 1)])

    # ── Serialización ────────────────────────────────────────────────────────
    def to_json(self, indent: int = 2) -> str:
        payload = {"kikolens_recipe": FORMAT_VERSION, "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                   "steps": [s.to_dict() for s in self.steps]}
        return json.dumps(payload, indent=indent, ensure_ascii=False)

    @classmethod
    def from_json(cls, text: str) -> "Recipe":
        try:
            payload = json.loads(text)
        except json.JSONDecodeError as e:
            raise ValueError(f"The recipe is not valid JSON: {e.msg}.") from None
        if not isinstance(payload, dict) or "steps" not in payload:
            raise ValueError("This file is not a KikoLens recipe.")
        if payload.get("kikolens_recipe", 0) > FORMAT_VERSION:
            raise ValueError("This recipe was made by a newer version of KikoLens.")
        steps = []
        for raw in payload["steps"]:
            if not isinstance(raw, dict) or raw.get("op") not in OPERATIONS or not isinstance(raw.get("params", {}), dict):
                raise ValueError(f"Unknown or malformed step: {raw.get('op') if isinstance(raw, dict) else raw!r}.")
            steps.append(Step(raw["op"], raw.get("params", {}), raw.get("message", "")))
        return cls(steps)

    def to_python(self, source: str = "data.csv") -> str:
        """Script que repite la receta con KikoLens: carga el archivo, aplica los pasos y guarda el resultado."""
        steps = json.dumps([s.to_dict() for s in self.steps], indent=4, ensure_ascii=False)
        return (
            '"""Generated by KikoLens: repeats the cleaning and transformation steps of a session."""\n'
            "import json\n\nfrom kikolens.pipeline.recipe import Recipe\nfrom kikolens.utils.loaders import load_data\n\n"
            f"STEPS = json.loads({steps!r})\n\n\n"
            "def run(path):\n"
            "    recipe = Recipe.from_json(json.dumps({\"kikolens_recipe\": 1, \"steps\": STEPS}))\n"
            "    df, log = recipe.apply(load_data(path))\n"
            "    for line in log:\n"
            "        print(\"-\", line)\n"
            "    return df\n\n\n"
            "if __name__ == \"__main__\":\n"
            f"    run({source!r}).to_csv(\"result.csv\", index=False)\n"
        )
