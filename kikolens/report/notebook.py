"""Cuaderno de Jupyter (.ipynb) que reproduce un análisis: carga los datos, repite la receta y, si se indica, entrena el modelo
y prevé la serie. Se genera como JSON a mano (formato nbformat 4), sin depender de ninguna biblioteca de cuadernos."""
import json
import textwrap


def _md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": textwrap.dedent(text).strip().splitlines(True)}


def _code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": textwrap.dedent(text).strip().splitlines(True)}


def build_notebook(source: str, recipe=None, target: str | None = None, drop=(), date: str | None = None, value: str | None = None,
                   horizon: int = 12, title: str = "KikoLens analysis") -> str:
    """El cuaderno como texto JSON. `recipe` es una `Recipe` (o None); `target` añade el laboratorio de modelos y
    `date`+`value` una previsión."""
    cells = [_md(f"# {title}\n\nGenerated by KikoLens. Run the cells in order; the data never leaves this computer."),
             _code("""
                import json
                import pandas as pd
                from kikolens.analyze.quality import profile_quality
                from kikolens.pipeline.recipe import Recipe
                from kikolens.utils.loaders import load_data
                """),
             _md("## Data"),
             _code(f"df = load_data({source!r})\ndf.head()")]
    if recipe is not None and len(recipe):
        steps = json.dumps([s.to_dict() for s in recipe.steps], indent=2, ensure_ascii=False)
        cells += [_md("## Cleaning and transformation steps\n\nThe same steps used in the dashboard."),
                  _code(f"STEPS = json.loads({steps!r})\n"
                        "recipe = Recipe.from_json(json.dumps({\"kikolens_recipe\": 1, \"steps\": STEPS}))\n"
                        "df, log = recipe.apply(df)\n"
                        "print(\"\\n\".join(f\"- {line}\" for line in log))")]
    cells += [_md("## Quality"),
              _code("quality = profile_quality(df)\nprint(f\"Quality score: {quality['score']}/100\")\nquality['columns']")]
    if target:
        cells += [_md(f"## Model for `{target}`\n\nSeveral models are compared with cross-validation on the training rows, "
                      "the best one is tuned, and it is tested once on rows set aside."),
                  _code("from kikolens.analyze.modellab import run_model_lab\n\n"
                        f"result = run_model_lab(df, {target!r}, drop={list(drop)!r})\n"
                        "print(result['narrative'])\nresult['leaderboard']"),
                  _code("result['plots']['leaderboard']")]
    if date and value:
        cells += [_md(f"## Forecast of `{value}`"),
                  _code("from kikolens.analyze import forecasting, timeseries\n\n"
                        f"series = timeseries.prepare_series(df, {date!r}, {value!r})\n"
                        f"forecast = forecasting.forecast_models(series, {int(horizon)})\n"
                        "print(forecast['summary'])\nforecasting.forecast_figure(series, forecast)")]
    notebook = {"nbformat": 4, "nbformat_minor": 4,
                "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                             "language_info": {"name": "python"}},
                "cells": cells}
    return json.dumps(notebook, indent=1, ensure_ascii=False) + "\n"
